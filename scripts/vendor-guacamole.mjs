import { readFile, readdir, mkdir, writeFile } from 'node:fs/promises'
import { join, resolve } from 'node:path'
import { createRequire } from 'node:module'

// Generate the browser dependency from unchanged Apache Guacamole 1.6.0 sources.
const upstream = resolve(process.argv[2])
const source = join(upstream, 'guacamole-common-js/src/main/webapp/modules')
const modules = (await readdir(source)).filter(name => name.endsWith('.js')).sort()
const content = (await Promise.all(modules.map(name => readFile(join(source, name), 'utf8')))).join('\n')
if (!content.includes('Guacamole.API_VERSION = "1.6.0"')) throw new Error('Expected Guacamole 1.6.0')
const require = createRequire(new URL('../web/package.json', import.meta.url))
const { build } = createRequire(require.resolve('vite/package.json'))('esbuild')
const target = new URL('../web/src/vendor/', import.meta.url)
await mkdir(target, { recursive: true })
await build({
  stdin: { contents: content + '\nexport default Guacamole;', loader: 'js' },
  outfile: new URL('guacamole.js', target).pathname.replace(/^\/([A-Za-z]:)/, '$1'),
  format: 'esm', minify: true, target: 'es2022',
  banner: { js: '/* Apache Guacamole 1.6.0 · Apache-2.0 · generated by scripts/vendor-guacamole.mjs */' },
})
for (const name of ['LICENSE', 'NOTICE'])
  await writeFile(new URL('guacamole.' + name, target), (await readFile(join(upstream, name), 'utf8')).trimEnd() + '\n')
